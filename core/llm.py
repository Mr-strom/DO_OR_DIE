def clean_json_response(raw_text: str) -> Dict[str, Any]:
    """
    Cleans markdown code fences (```json ... ```) and extracts parsed JSON.
    Falls back to regex brace matching if surrounding text exists.
    """
    text = raw_text.strip()
    # Strip ```json or ```
    text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"\s*```$", "", text, flags=re.MULTILINE)
    text = text.strip()

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        # Try to locate the outermost JSON object
        match = re.search(r"(\{.*\})", text, re.DOTALL)
        if match:
            try:
                return json.loads(match.group(1))
            except json.JSONDecodeError:
                pass
        return {"raw_response": text, "error": "Could not parse JSON"}


def _get_api_key(key_name: str) -> Optional[str]:
    """Retrieves API key from Streamlit secrets or OS environment variables."""
    if HAS_STREAMLIT:
        try:
            val = st.secrets.get(key_name)
            if val:
                return str(val).strip()
        except Exception:
            pass
    return os.environ.get(key_name, "").strip() or None


