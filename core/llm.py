def call_llm(
    prompt: str,
    system_prompt: str = "",
    schema_type: str = "general"
) -> Dict[str, Any]:
    """
    Executes hybrid LLM call:
    1. Tries Gemini if GEMINI_API_KEY is available.
    2. Tries Groq if GROQ_API_KEY is available.
    3. Seamlessly falls back to high-fidelity domain-specific demo mock data.
    """
    gemini_key = _get_api_key("GEMINI_API_KEY")
    if gemini_key and HAS_GEMINI:
        try:
            genai.configure(api_key=gemini_key)
            model = genai.GenerativeModel(
                model_name="gemini-1.5-flash",
                system_instruction=system_prompt if system_prompt else None
            )
            full_prompt = f"{prompt}\n\nPlease respond exclusively with valid JSON conforming to {schema_type} format."
            response = model.generate_content(full_prompt)
            if response and response.text:
                parsed = clean_json_response(response.text)
                if "error" not in parsed:
                    parsed["_engine"] = "gemini-live"
                    return parsed
        except Exception:
            pass

    groq_key = _get_api_key("GROQ_API_KEY")
    if groq_key and HAS_GROQ:
        try:
            client = Groq(api_key=groq_key)
            messages = []
            if system_prompt:
                messages.append({"role": "system", "content": system_prompt})
            messages.append({"role": "user", "content": f"{prompt}\nReturn JSON only."})
            completion = client.chat.completions.create(
                model="llama-3.1-8b-instant",
                messages=messages,
                response_format={"type": "json_object"},
                temperature=0.2,
                timeout=5.0
            )
            content = completion.choices[0].message.content
            if content:
                parsed = clean_json_response(content)
                if "error" not in parsed:
                    parsed["_engine"] = "groq-live"
                    return parsed
        except Exception:
            pass

    # High-fidelity demo fallback with subtle micro-latency simulation
    time.sleep(0.05)
    fallback = _get_fallback_payload(schema_type, prompt)
    fallback["_engine"] = "demo-safety-fallback"
    return fallback
